// Weekday abbreviations, index 0 = Sunday .. 6 = Saturday (matches the
// schema's days_of_week convention).
const DAY_ABBREVS: Record<string, string[]> = {
  en: ['S', 'M', 'T', 'W', 'T', 'F', 'S'],
  es: ['D', 'L', 'M', 'X', 'J', 'V', 'S'],
  fr: ['D', 'L', 'M', 'M', 'J', 'V', 'S'],
  de: ['S', 'M', 'D', 'M', 'D', 'F', 'S'],
  pt: ['D', 'S', 'T', 'Q', 'Q', 'S', 'S'],
  hi: ['र', 'सो', 'मं', 'बु', 'गु', 'शु', 'श'],
  zh: ['日', '一', '二', '三', '四', '五', '六'],
  ja: ['日', '月', '火', '水', '木', '金', '土'],
};

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => String(params[key] ?? ''));
}

export function useTranslation() {
  const { language } = useAuth();
  const strings = STRINGS[language] ?? STRINGS.en;

  const t = (key: Key, params?: Record<string, string | number>): string => {
    const template = strings[key] ?? STRINGS.en[key] ?? key;
    return interpolate(template, params);
  };

  const dayAbbrevs = DAY_ABBREVS[language] ?? DAY_ABBREVS.en;

  return { t, language, dayAbbrevs };
}
